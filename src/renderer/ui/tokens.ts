function block(selector: string, vars: Record<string, string>): string {
  const lines = Object.entries(vars).map(([name, value]) => `  --moss-${name}: ${value};`)
  return `${selector} {\n${lines.join('\n')}\n}\n`
}

/** Renders the full tokens.css text. Pure; shared by the generator script and the sync test. */
export function renderTokensCss(p: Palette): string {
  return [
    '/* Generated by `npm run gen:tokens` from src/renderer/ui/tokens.ts. Do not edit. */\n',
    block(':root', staticTokens),
    block(':root[data-theme="light"]', p.light).replace('{\n', '{\n  color-scheme: light;\n'),
    block(':root[data-theme="dark"]', p.dark).replace('{\n', '{\n  color-scheme: dark;\n')
  ].join('\n')
}
